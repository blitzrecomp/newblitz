#!/bin/sh
# The cart season (src/cart: season.c, stubs.S) for the N64: LLVM (Homebrew's llvm, or LLVM=<bin dir>) for MIPS II,
# o32, linked twice (src/cart/link.ld): at 0x800E4700 for Lite: Season (the default heap's old top, any N64) and at
# 0x80400000 for Full (the Expansion Pak) -> src/game/cart_season.inc, which Export ROM appends to 32-team carts.
set -e
cd "$(dirname "$0")/../.."
LLVM=${LLVM:-/opt/homebrew/opt/llvm/bin}
OUT=build/cart
mkdir -p $OUT
FLAGS="--target=mips-none-elf -march=mips2 -mabi=32 -mfp32 -mno-abicalls -fno-pic -G0 -O2 -ffreestanding -fno-builtin \
  -fno-zero-initialized-in-bss -fno-stack-protector -mno-check-zero-division -mno-odd-spreg -Wall -Wextra -Wno-unused-parameter"
$LLVM/clang $FLAGS -c src/cart/season.c -o $OUT/season.o
$LLVM/clang $FLAGS -c src/cart/stubs.S -o $OUT/stubs.o
for v in "lean 0x800E4700 0x800EE700" "pak 0x80400000 0x80800000"; do
    set -- $v
    /opt/homebrew/bin/ld.lld -T src/cart/link.ld --defsym SEASON_BASE=$2 --defsym SEASON_END=$3 --no-check-sections \
        -o $OUT/season_$1.elf $OUT/stubs.o $OUT/season.o
    $LLVM/llvm-objcopy -O binary $OUT/season_$1.elf $OUT/season_$1.bin
    $LLVM/llvm-nm $OUT/season_$1.elf > $OUT/season_$1.sym
done
python3 - <<'PY'
out = "// Generated by tools/cart/build.sh from src/cart (season.c, stubs.S): don't edit. The cart season, linked for\n"
out += "// Lite: Season at 0x800E4700 (the default heap's old top, any N64) and for Full at 0x80400000 (the Expansion Pak); its\n"
out += "// league block (cart_season.h CartLeague) at +0x40 is filled by the export.\n"
for name, base, end in (("lean", 0x800E4700, 0x800EE700), ("pak", 0x80400000, 0x80800000)):
    data = open(f"build/cart/season_{name}.bin", "rb").read()
    data += bytes((-len(data)) % 8)
    sym = {}
    for line in open(f"build/cart/season_{name}.sym"):
        p = line.split()
        if len(p) == 3:
            sym[p[2]] = int(p[0], 16)
    assert sym["cs_entry"] == base and sym["cs_league_space"] == base + 0x40, sym
    assert base + len(data) <= end, f"the season ({len(data)} bytes) is bigger than its room"
    words = [int.from_bytes(data[i:i + 4], "big") for i in range(0, len(data), 4)]
    body = ",\n    ".join(", ".join(f"0x{w:08X}" for w in words[i:i + 8]) for i in range(0, len(words), 8))
    out += f"constexpr uint32_t cart_season_{name}[] = {{\n    {body}\n}};\n"
    out += f"constexpr uint32_t cart_season_{name}_vram = 0x{base:08X};\n"
    print(f"-> src/game/cart_season.inc: {name} {len(data)} bytes at 0x{base:08X}")
open("src/game/cart_season.inc", "w").write(out)
PY
