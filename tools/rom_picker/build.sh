#!/bin/sh
# Assembles picker.asm, rules.asm, opponent.asm, order.asm, order_orig.asm and lookup.asm (armips: https://github.com/Kingcom/armips, on PATH or in build/tools; ARMIPS=<path> to override) into
# src/game/rom_picker_code.inc: the code Export ROM writes over libultra functions the game never calls.
set -e
cd "$(dirname "$0")"
[ -z "$ARMIPS" ] && [ -x ../../build/tools/armips ] && ARMIPS=../../build/tools/armips  # a local build kept in build/tools
"${ARMIPS:-armips}" -equ ORIG 0 picker.asm
"${ARMIPS:-armips}" -equ ORIG 1 -sym picker_orig.sym picker.asm
"${ARMIPS:-armips}" rules.asm
"${ARMIPS:-armips}" -sym opponent.sym opponent.asm
"${ARMIPS:-armips}" -sym order.sym order.asm
"${ARMIPS:-armips}" -sym order_orig.sym order_orig.asm
"${ARMIPS:-armips}" -equ CODE 0x800F1110 -equ CLASH_TABLE 0x800F0D10 -equ END 0x800F2700 -sym cart32.sym cart32.asm
"${ARMIPS:-armips}" -equ FS40 0 lookup.asm
"${ARMIPS:-armips}" -equ FS40 1 lookup.asm
python3 - <<'PY'
def words(name, size):
    data = open(name, "rb").read()
    assert len(data) <= size, (name, len(data))
    data += bytes(size - len(data))
    w = [int.from_bytes(data[i:i + 4], "big") for i in range(0, len(data), 4)]
    return ",\n    ".join(", ".join(f"0x{x:08X}" for x in w[i:i + 8]) for i in range(0, len(w), 8))
out = "// Generated by tools/rom_picker/build.sh from picker.asm, rules.asm, opponent.asm, order.asm and lookup.asm: don't edit.\n"
out += "// The Uniform Picker at 0x8001C0A0 (over guLookAtF, boot ROM 0x1CCA0), 0x380 bytes.\n"
out += "constexpr uint32_t rom_picker_code[] = {\n    " + words("picker.bin", 0x380) + "\n};\n"
out += "constexpr uint32_t rom_picker_vram = 0x8001C0A0, rom_picker_counts = 0x8001C380, rom_picker_table = 0x8001C3A8;\n"
out += "// The VS-screen rules and the kickoff touchback at 0x8001D040 (over guPositionF and guPosition), 0x3C0 bytes.\n"
out += "constexpr uint32_t rom_rules_code[] = {\n    " + words("rules.bin", 0x3C0) + "\n};\n"
out += "constexpr uint32_t rom_rules_vram = 0x8001D040, rom_rules_touchback = 0x8001D124, rom_rules_flags = 0x8001D300,\n"
out += "                   rom_rules_flags_play = 0x8001D360, rom_rules_home = 0x8001D3C0, rom_rules_tb_spot = 0x8001D3E4;\n"
def symbols(name):
    out = {}
    for line in open(name):
        p = line.split()
        if len(p) == 2 and not p[1].startswith("@"):
            out[p[1].lower()] = int(p[0], 16)
    return out
sym = {}
for line in open("opponent.sym"):
    p = line.split()
    if len(p) == 2 and not p[1].startswith("@"):
        sym[p[1].lower()] = int(p[0], 16)
assert sym["woken"] == 0x8001D160, hex(sym["woken"])
out += "// Choose CPU Opponent at 0x8001CBD0 (over guMtxIdent and guPerspectiveF), 0x2A0 bytes, and 0x8001D160 (the rules\n"
out += "// cave's free tail, 0x1A0 bytes: written after the rules code); its entry points and state.\n"
out += "constexpr uint32_t rom_opp_code[] = {\n    " + words("opponent.bin", 0x2A0) + "\n};\n"
out += "constexpr uint32_t rom_opp_code2[] = {\n    " + words("opponent2.bin", 0x1A0) + "\n};\n"
out += "constexpr uint32_t rom_opp_code3[] = {\n    " + words("opponent3.bin", 0xC0) + "\n};\n"
out += "constexpr uint32_t rom_opp_vram = 0x8001CBD0, rom_opp_vram2 = 0x8001D160, rom_opp_vram3 = 0x800277F0"
for k in ("reset", "wake", "setup", "in_a", "in_b", "in_c", "panel", "hold", "restore", "woken", "order_at"):
    out += f",\n                   rom_opp_{k} = 0x{sym[k]:08X}"
out += ";\n"
po = symbols("picker_orig.sym")
out += "// The same for the original game (picker.asm -equ ORIG 1): main's uniform tables, and a reset at team select's start.\n"
out += "constexpr uint32_t rom_picker_orig_code[] = {\n    " + words("picker_orig.bin", 0x380) + "\n};\n"
out += "constexpr uint32_t rom_picker_orig_code2[] = {\n    " + words("picker_orig2.bin", 0xE0) + "\n};\n"
out += "constexpr uint32_t rom_picker_orig_code3[] = {\n    " + words("picker_orig3.bin", 0x80) + "\n};\n"
out += "constexpr uint32_t rom_picker_orig_vram2 = 0x80019A58, rom_picker_orig_vram3 = 0x8001F890;\n"
out += f"constexpr uint32_t rom_picker_orig_reset = 0x{po['reset']:08X}, rom_picker_orig_next = 0x{po['next']:08X}, rom_picker_orig_uni = 0x{po['uni']:08X};\n"
assert po["counts"] == 0x8001C380 and po["table"] == 0x8001C3A8, (hex(po["counts"]), hex(po["table"]))
o = symbols("order.sym")
out += "// Team select in name order at 0x80024EC0 (over osPfsIsPlug), 0x17C bytes; its entry points and tables.\n"
out += "constexpr uint32_t rom_order_code[] = {\n    " + words("order.bin", 0x17C) + "\n};\n"
out += "constexpr uint32_t rom_order_vram = 0x80024EC0"
for k in ("moved", "above", "below", "n", "order", "pos"):
    out += f",\n                   rom_order_{k} = 0x{o[k]:08X}"
out += ";\n"
o = symbols("order_orig.sym")
out += "// Team select in name order on the original game at 0x80024EC0 (over osPfsIsPlug); its entry points and tables.\n"
out += "constexpr uint32_t rom_order_orig_code[] = {\n    " + words("order_orig.bin", 0x17C) + "\n};\n"
out += "constexpr uint32_t rom_order_orig_vram = 0x80024EC0"
for k in ("reset", "moved", "above_0", "above_n", "below_0", "below_n", "next", "cur", "n", "order", "pos"):
    out += f",\n                   rom_order_orig_{k} = 0x{o[k]:08X}"
out += ";\n"
c = symbols("cart32.sym")
out += "// Houston on the cart (cart32.asm): the loader over osPfsIsPlug, and the code in the loaded block (engine32_layout.h cart).\n"
out += "constexpr uint32_t rom_cart32_boot[] = {\n    " + words("cart32_boot.bin", 0x17C) + "\n};\n"
data = open("cart32.bin", "rb").read()
out += "constexpr uint32_t rom_cart32_code[] = {\n    " + words("cart32.bin", (len(data) + 3) & ~3) + "\n};\n"
out += "constexpr uint32_t rom_cart32_vram = 0x800F1110, rom_cart32_boot_vram = 0x80024EC0"
for k in ("load", "block", "season", "reset", "moved", "above_0", "above_n", "below_0", "below_n", "clash", "next", "cur", "order", "pos"):
    out += f",\n                   rom_cart32_{k} = 0x{c[k]:08X}"
out += ";\n"
out += "// File lookup past the sorted TOC at 0x8001C9B4 (over guMtxXFML), 0x8C bytes: boot 0x80001CDC calls it.\n"
out += "constexpr uint32_t rom_lookup_code[] = {\n    " + words("lookup.bin", 0x8C) + "\n};\n"
out += "constexpr uint32_t rom_lookup40_code[] = {\n    " + words("lookup40.bin", 0x8C) + "\n};\n"
out += "constexpr uint32_t rom_lookup_vram = 0x8001C9B4;\n"
open("../../src/game/rom_picker_code.inc", "w").write(out)
print("-> src/game/rom_picker_code.inc")
PY
rm -f picker.bin rules.bin opponent.bin opponent2.bin opponent3.bin opponent.sym order.bin order.sym lookup.bin lookup40.bin order_orig.bin order_orig.sym picker_orig.bin picker_orig2.bin picker_orig3.bin picker_orig.sym cart32.bin cart32_boot.bin cart32.sym
