#!/usr/bin/env python3
"""Modern Blitz on the original game (src/game/engine32.cpp): blitz2000.toml plus this engine's hooks and the
instruction patches that move the team tables to 32-team copies (src/game/engine32_layout.h), written to
build/engine32/blitz2000.toml with its output in build/engine32/RecompiledFuncs. The Classic build's own code
(build/RecompiledFuncs) is never touched.

  python3 tools/engine32_toml.py && build/n64recomp/N64Recomp build/engine32/blitz2000.toml

The patches come from the disassembly (build/dis, `make syms`): every %hi/%lo pair whose address falls in one of
the tables is moved by the table's offset. A lui shared with an address outside the tables would be an error.
"""
import glob
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HOOKS = [
    ("ovl_b_func_802F90B8", 0x802F9B74, "ctx->r22 = blitz_v32_moved(rdram, (int32_t)ctx->r21, (int32_t)(int16_t)ctx->r22);"),
    ("ovl_b_func_802FA080", 0x802FA3C4, "ctx->r19 = blitz_v32_row(rdram, (int32_t)(int16_t)ctx->r19 + 1, -1);"),
    ("ovl_b_func_802FA080", 0x802FA4F8, "ctx->r19 = blitz_v32_row(rdram, (int32_t)(int16_t)ctx->r19 - 1, 1);"),
    # The row it draws: the game then wraps s3 >= 31 to 0 (s1, 0x802FA504), which drew Houston (31) as Arizona.
    ("ovl_b_func_802FA080", 0x802FA514, "ctx->r17 = ctx->r19;"),
    ("func_80001C2C", 0x80001CDC, "blitz_fs_scan(rdram, ctx);"),  # files added by name past the sorted TOC (art_dropin.cpp)
    # The jersey clash for this game's two teams (the game's 31 x 31 table can't hold 32): from the team store.
    ("ovl_b_func_802F5360", 0x802F5568, "ctx->r2 = blitz_e32_clash(rdram);"),
    # The season schedule's opponents by list name, as team+ shows them (the game prints the city, so both Los Angeles
    # teams read LOS ANGELES; it special-cases only the two New York teams). v1 = the team.
    ("ovl_b_func_80301604", 0x803017A8, "ctx->r7 = blitz_e32_list_name((int32_t)ctx->r3);"),
    # The BlitzRecomp credits page: the Players Inc screen's function run with our image, once, before the attract
    # sequence's New Features screen (engine32.cpp).
    ("ovl_b_func_802F0614", 0x802F0650, "ctx->r4 = blitz_e32_screen_image((int32_t)ctx->r4);"),
    ("ovl_b_func_802F02C4", 0x802F02C4, "blitz_e32_credits(rdram, ctx);"),
]
# Plain instruction changes: (function, address, the game's word, ours).
WORDS = [
    # The VS screen scans the moved right-helmet list's 32 entries, not the game's 9.
    ("func_8024C264", 0x8024C680, 0x28820009, 0x28820020),
    # A guest's (no player record) and the attract demo's CPU team: rand(32), not rand(31), so Houston comes up too.
    ("ovl_b_func_802F8594", 0x802F8A84, 0x2404001F, 0x24040020),
    ("ovl_b_func_802F8594", 0x802F8B84, 0x2404001F, 0x24040020),
]
# Which code can see a table: ovl_b's (menus) and ovl_a's (games) data share addresses.
VISIBLE = {"team": ("ovl_b", "main"), "select": ("ovl_b", "main"), "win": ("ovl_a", "main"), "ez1": ("ovl_a", "main"), "ez2": ("ovl_a", "main"), "ez3": ("ovl_a", "main"),
           "logo30": ("ovl_a", "main"), "selector": ("ovl_a", "main"), "cpu_off": ("ovl_a", "main"), "cpu_def": ("ovl_a", "main")}
ENTRIES = 31  # the original tables


def layout():
    text = (ROOT / "src" / "game" / "engine32_layout.h").read_text()
    out = {}
    for m in re.finditer(r'\{"(\w+)",\s*(0x[0-9A-F]+),\s*(0x[0-9A-F]+),\s*(0x[0-9A-F]+)\}', text):
        out[m.group(1)] = (int(m.group(2), 16), int(m.group(3), 16), int(m.group(4), 16))
    return out


def function_names():
    syms = tomllib.loads((ROOT / "build" / "syms" / "blitz2000.syms.toml").read_text())
    return {s["name"]: [(f["vram"], f["vram"] + f["size"], f["name"]) for f in s["functions"]] for s in syms["section"]}


sites = {}  # (seg, vram) -> (original word, table, offset in it, is the %hi): relocation_patches fills it


def write_sites(path):
    """The relocated sites for Export ROM's 32-team cart (src/game/export_rom.cpp), which puts the tables elsewhere:
    per site its segment, address, table and offset; the export reads the instruction from the ROM and checks it."""
    names = list(layout().keys())
    seg_id = {"main": 0, "ovl_a": 1, "ovl_b": 2}
    out = ["// Generated by tools/engine32_toml.py from the disassembly: don't edit. {segment (0 main, 1 ovl_a, 2 ovl_b),",
           "// address, table (engine32_layout.h order), offset in the table, 1 for the %hi}",
           "constexpr E32Site e32_sites[] = {"]
    for (seg, vram), (word, t, off, hi) in sorted(sites.items()):
        out.append(f"    {{{seg_id[seg]}, 0x{vram:08X}, 0x{word:08X}, {names.index(t)}, 0x{off:X}, {1 if hi else 0}}},")
    out.append("};")
    Path(path).write_text("\n".join(out) + "\n")


def relocation_patches():
    tables = layout()
    funcs = function_names()

    def table_of(seg, a):
        for name, (orig, entry, now) in tables.items():  # a table's own address first (the lists sit side by side)
            if a == orig and seg in VISIBLE.get(name, ("main", "ovl_a", "ovl_b", "boot")):
                return name
        for name, (orig, entry, now) in tables.items():
            if orig <= a < orig + entry * ENTRIES and seg in VISIBLE.get(name, ("main", "ovl_a", "ovl_b", "boot")):
                return name
        return None

    def func_at(seg, vram):
        for lo, hi, name in funcs[seg]:
            if lo <= vram < hi:
                return name
        raise SystemExit(f"no function at {seg} {vram:08X}")

    ins = re.compile(r'/\* [0-9A-F]+ ([0-9A-F]{8}) ([0-9A-F]{8}) \*/\s+(\S+)\s+(.*)')
    sym = re.compile(r'%(hi|lo)\(D_(?:FLT_)?([0-9A-F]{8})(?:\s*\+\s*(0x[0-9A-F]+))?\)')
    patches = {}  # (seg, vram) -> (func, word, comment)
    sites.clear()
    for f in sorted(glob.glob(str(ROOT / "build" / "dis" / "*_text" / "*.s"))):
        seg = Path(f).parent.name.replace("_text", "")
        if seg not in funcs:
            continue
        last_hi = {}  # register -> (vram, word, target table)
        for line in open(f):
            if line.startswith("glabel"):
                last_hi = {}
            m = ins.search(line)
            if not m:
                continue
            vram, word, op, args = int(m.group(1), 16), int(m.group(2), 16), m.group(3), m.group(4)
            regs = re.findall(r'\$(\w+)', args)
            s = sym.search(args)
            if s:
                a = int(s.group(2), 16) + (int(s.group(3), 16) if s.group(3) else 0)
                t = table_of(seg, a)
                if s.group(1) == "hi":
                    last_hi[regs[0]] = (vram, word, t, a)
                    continue
                base = regs[-1] if "(" in args else (regs[1] if len(regs) > 1 else regs[0])
                h = last_hi.get(base)
                if t is None:
                    if h and h[2] is not None:
                        raise SystemExit(f"{seg} {vram:08X}: a table's lui also serves {a:08X}")
                    continue
                if h is None:
                    raise SystemExit(f"{seg} {vram:08X}: no lui found for {a:08X}")
                orig, entry, now = tables[t]
                new = a - orig + now
                if (new & 0xFFFF) >= 0x8000:
                    raise SystemExit(f"{t}: {new:08X} needs a carried upper half")
                fn = func_at(seg, vram)
                patches[(seg, vram)] = (fn, (word & 0xFFFF0000) | (new & 0xFFFF), f"%lo {t} +{a - orig:#x}")
                sites[(seg, vram)] = (word, t, a - orig, False)
                hi_new = (h[1] & 0xFFFF0000) | (new >> 16)
                old = patches.get((seg, h[0]))
                if old and old[1] != hi_new:
                    raise SystemExit(f"{seg} {h[0]:08X}: one lui, two upper halves")
                patches[(seg, h[0])] = (func_at(seg, h[0]), hi_new, f"%hi {t}")
                sites[(seg, h[0])] = (h[1], t, a - orig, True)
            elif regs and op not in ("sw", "sh", "sb", "swc1", "sd", "sdc1", "beq", "bne", "beqz", "bnez", "blez", "bgtz",
                                     "bltz", "bgez", "beql", "bnel", "jr", "jal", "j", "mtc1"):
                if op in ("addu", "add") and len(regs) == 3 and regs[0] in last_hi and regs[0] in regs[1:]:
                    continue  # the table address plus an index
                last_hi.pop(regs[0], None)
    return patches


def main():
    src = (ROOT / "blitz2000.toml").read_text()
    old = 'output_func_path = "build/RecompiledFuncs"'
    assert old in src
    src = src.replace(old, 'output_func_path = "build/engine32/RecompiledFuncs"')
    src = src.replace('"build/', f'"{ROOT}/build/')  # N64Recomp reads paths relative to the file
    for func, vram, text in HOOKS:
        src += f'\n[[patches.hook]]\nfunc = "{func}"\nbefore_vram = 0x{vram:08X}\ntext = "    {text}"\n'
    # Season (the Advanced engine and the 32-team Standard Season) and league paks (the main menu's modes, announcer
    # banks): the same hooks as Modern's team+ build (tools/teamplus.py), where the original game has the same
    # instruction (all but team+'s own team count).
    sys.path.insert(0, str(ROOT / "tools"))
    import teamplus
    rom = (ROOT / "build" / "baserom.z64").read_bytes()
    funcs = function_names()
    rom_at = {"main": lambda v: 0x2FC20 + v - 0x80248F00, "ovl_b": lambda v: 0xDE350 + v - 0x802EFE70}
    added = skipped = 0
    for sec, vram, (chk, want), hook, comment in teamplus.ADVANCED + teamplus.SEASON32 + teamplus.LEAGUE:
        o = rom_at[sec](chk)
        if int.from_bytes(rom[o:o + 4], "big") != want:
            skipped += 1
            continue
        fn = next(name for lo, hi, name in funcs[sec] if lo <= vram < hi)
        src += f'\n[[patches.hook]]\nfunc = "{fn}"\nbefore_vram = 0x{vram:08X}\ntext = "    {hook}"\n'
        added += 1
    print(f"season hooks: {added} added, {skipped} where the original game differs")
    patches = relocation_patches()
    for func, vram, was, now in WORDS:
        seg_rom = rom_at["main"](vram) if vram < 0x802EFE70 else rom_at["ovl_b"](vram)
        if int.from_bytes(rom[seg_rom:seg_rom + 4], "big") != was:
            raise SystemExit(f"{vram:08X} isn't {was:08X}")
        patches[("main", vram)] = (func, now, "32-team change")
    src += "\n# ---- the team tables at their 32-team addresses (src/game/engine32_layout.h) ----\n"
    for (seg, vram), (func, word, comment) in sorted(patches.items()):
        src += f'[[patches.instruction]]\nfunc = "{func}"\nvram = 0x{vram:08X}\nvalue = 0x{word:08X}  # {comment}\n'
    out = ROOT / "build" / "engine32" / "blitz2000.toml"
    out.parent.mkdir(parents=True, exist_ok=True)  # before the first write: a fresh clone has no build/engine32
    write_sites(ROOT / "build" / "engine32" / "engine32_sites.inc")
    out.write_text(src)
    print(f"wrote {out.relative_to(ROOT)}: {len(HOOKS)} hooks, {len(patches)} instruction patches")


if __name__ == "__main__":
    main()
